-- ---------- Limpieza (permite volver a ejecutar el script) ----------
-- IF EXISTS requiere Oracle 23ai o superior (lo normal en una base nueva de Oracle Cloud)
DROP TABLE IF EXISTS paso;
DROP TABLE IF EXISTS ingrediente;
DROP TABLE IF EXISTS receta;

-- ---------- Tablas ----------
CREATE TABLE receta (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre              VARCHAR2(100)  NOT NULL,
    descripcion         VARCHAR2(500)  NOT NULL,
    tipo_cocina         VARCHAR2(50)   NOT NULL,
    pais                VARCHAR2(50)   NOT NULL,
    dificultad          VARCHAR2(20)   NOT NULL,
    tiempo_preparacion  NUMBER(4)      NOT NULL,
    tiempo_coccion      NUMBER(4)      NOT NULL,
    porciones           NUMBER(3)      NOT NULL,
    imagen              VARCHAR2(100),
    fecha_publicacion   DATE           NOT NULL,
    visitas             NUMBER(10)     DEFAULT 0 NOT NULL,
    CONSTRAINT ck_receta_dificultad CHECK (dificultad IN ('Fácil', 'Media', 'Difícil')),
    CONSTRAINT ck_receta_tiempos    CHECK (tiempo_preparacion >= 0 AND tiempo_coccion >= 0)
);

CREATE TABLE ingrediente (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id    NUMBER         NOT NULL,
    orden        NUMBER(3)      NOT NULL,
    descripcion  VARCHAR2(200)  NOT NULL,
    CONSTRAINT fk_ingrediente_receta FOREIGN KEY (receta_id) REFERENCES receta (id) ON DELETE CASCADE
);

CREATE TABLE paso (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id    NUMBER         NOT NULL,
    numero       NUMBER(3)      NOT NULL,
    descripcion  VARCHAR2(500)  NOT NULL,
    CONSTRAINT fk_paso_receta FOREIGN KEY (receta_id) REFERENCES receta (id) ON DELETE CASCADE
);

CREATE INDEX ix_ingrediente_receta ON ingrediente (receta_id);
CREATE INDEX ix_paso_receta        ON paso (receta_id);

